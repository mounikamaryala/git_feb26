public class Assignment2 {
	public static void main (String[] args)
	{
		float ft=97.8f;
		double ftdouble= ft;
		System.out.println(ftdouble);//upcasting
		int ftint=(int)ft;
		System.out.println(ftint);//downcasting
		 
		char charvalue= (char)ftint;
		System.out.println(charvalue);
		
	}

}
